import React, { useState } from 'react';
import { HelpCircle, X } from 'lucide-react';

const METRIC_FORMULAS = {
  net_sales: {
    title: 'Net Sales',
    formula: 'Gross Sales − Customer Discounts − Returns & Refunds',
    detail: 'Total realized revenue across all orders after deducting line item discounts and returned items.',
  },
  cogs: {
    title: 'Cost of Goods Sold (COGS)',
    formula: 'Sum(Units Sold × Unit Weighted Purchase Cost)',
    detail: 'The direct procurement cost of all inventory units sold during the selected period, calculated at cost price.',
  },
  gross_profit: {
    title: 'Gross Profit',
    formula: 'Net Sales − COGS',
    detail: 'Profit before operating expenses, showing raw product margin performance.',
  },
  gross_margin_pct: {
    title: 'Gross Margin %',
    formula: '(Gross Profit ÷ Net Sales) × 100',
    detail: 'Gross profit expressed as a percentage of Net Sales.',
  },
  operating_expenses: {
    title: 'Operating Expenses (OpEx)',
    formula: 'Store Rent + Utilities + Approved Payroll + Logistics + Other Vouchers',
    detail: 'All operating overheads recorded in the ledger, including auto-posted monthly payroll vouchers.',
  },
  net_profit: {
    title: 'Net Profit',
    formula: 'Gross Profit − Operating Expenses',
    detail: 'Final bottom line profit generated by the business. Negative value indicates a net operating deficit.',
  },
  aov: {
    title: 'Average Order Value (AOV)',
    formula: 'Net Sales ÷ Total Completed Orders',
    detail: 'Average basket size per successful transaction across customer checkouts.',
  },
};

export function MetricFormulaTooltip({ metricKey, children }) {
  const [open, setOpen] = useState(false);
  const info = METRIC_FORMULAS[metricKey];

  if (!info) return children || null;

  return (
    <div className="relative inline-flex items-center">
      {children}
      <button
        type="button"
        onClick={() => setOpen(!open)}
        className="ml-1 text-slate-400 hover:text-admin-600 dark:hover:text-admin-400 focus:outline-none transition-colors"
        title={`View formula for ${info.title}`}
      >
        <HelpCircle className="w-3.5 h-3.5" />
      </button>

      {open && (
        <>
          <div
            className="fixed inset-0 z-40"
            onClick={() => setOpen(false)}
          />
          <div className="absolute left-0 bottom-full mb-2 z-50 w-72 p-3 bg-slate-900 text-white rounded-xl shadow-xl border border-slate-800 text-xs animate-fadeIn">
            <div className="flex items-center justify-between pb-1 mb-1 border-b border-slate-800">
              <span className="font-semibold text-admin-300">{info.title}</span>
              <button
                onClick={() => setOpen(false)}
                className="text-slate-400 hover:text-white"
              >
                <X className="w-3.5 h-3.5" />
              </button>
            </div>
            <div className="font-mono text-[11px] text-emerald-400 bg-slate-950 p-1.5 rounded my-1.5 border border-slate-800/80">
              {info.formula}
            </div>
            <p className="text-slate-300 text-[11px] leading-relaxed">
              {info.detail}
            </p>
          </div>
        </>
      )}
    </div>
  );
}

export default MetricFormulaTooltip;
